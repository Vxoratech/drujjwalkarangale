/** Central query-key factory. Every key starts with the clinic id so switching tenants never reuses cache. */
export const qk = {
  memberships: (userId: string) => ['memberships', userId] as const,
  permissions: (clinicId: string) => [clinicId, 'permissions'] as const,
  clinic: (clinicId: string) => [clinicId, 'clinic'] as const,
  branches: (clinicId: string) => [clinicId, 'branches'] as const,
  staff: (clinicId: string) => [clinicId, 'staff'] as const,
  doctors: (clinicId: string) => [clinicId, 'doctors'] as const,
  profile: (userId: string) => ['profile', userId] as const,
  dashboard: (clinicId: string) => [clinicId, 'dashboard'] as const,
  patients: (clinicId: string, params?: object) => [clinicId, 'patients', params ?? {}] as const,
  patient: (clinicId: string, id: string) => [clinicId, 'patient', id] as const,
  appointments: (clinicId: string, params?: object) => [clinicId, 'appointments', params ?? {}] as const,
  appointment: (clinicId: string, id: string) => [clinicId, 'appointment', id] as const,
  consultations: (clinicId: string, params?: object) => [clinicId, 'consultations', params ?? {}] as const,
  consultation: (clinicId: string, id: string) => [clinicId, 'consultation', id] as const,
  prescriptions: (clinicId: string, params?: object) => [clinicId, 'prescriptions', params ?? {}] as const,
  prescription: (clinicId: string, id: string) => [clinicId, 'prescription', id] as const,
  investigations: (clinicId: string, params?: object) => [clinicId, 'investigations', params ?? {}] as const,
  invoices: (clinicId: string, params?: object) => [clinicId, 'invoices', params ?? {}] as const,
  invoice: (clinicId: string, id: string) => [clinicId, 'invoice', id] as const,
  reports: (clinicId: string, params?: object) => [clinicId, 'reports', params ?? {}] as const,
  audit: (clinicId: string, params?: object) => [clinicId, 'audit', params ?? {}] as const,
  notifications: (clinicId: string) => [clinicId, 'notifications'] as const,
};
